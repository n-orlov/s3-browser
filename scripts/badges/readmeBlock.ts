// Pure generation of the README badge row (no I/O). `readme.ts` (`npm run badges:readme`) reads package.json and
// README.md, calls `readmeBadgeBlock` and `replaceBadgeBlock`, and writes README.md back.
import { BADGE_NAMES, staticBadges } from './badges.ts';

export const BLOCK_START = '<!-- badges:start (generated by `npm run badges:readme`; do not edit) -->';
export const BLOCK_END = '<!-- badges:end -->';

export const REPO_URL = 'https://github.com/n-orlov/s3-browser';
export const PAGES_URL = 'https://n-orlov.github.io/s3-browser';

/** The workflow files that get a status badge, with their display names. */
export const WORKFLOW_BADGES = [
  { file: 'ci.yml', name: 'CI' },
  { file: 'codeql.yml', name: 'CodeQL' },
  { file: 'mutation.yml', name: 'Mutation' },
  { file: 'e2e-soak.yml', name: 'E2E soak' },
] as const;

/** URL of the endpoint JSON file the publish job writes for a metric badge. */
export const metricJsonUrl = (name: string): string => `${PAGES_URL}/badges/${name}.json`;

const image = (alt: string, src: string, link: string): string => `[![${alt}](${src})](${link})`;

function staticImage(label: string, message: string): string {
  const part = (text: string): string => encodeURIComponent(text).replaceAll('-', '--');
  return `https://img.shields.io/badge/${part(label)}-${part(message)}-blue`;
}

/** The marker-delimited badge block (markers included, no trailing newline). */
export function readmeBadgeBlock(pkg: unknown): string {
  const lines: string[] = [];
  for (const { file, name } of WORKFLOW_BADGES) {
    const workflow = `${REPO_URL}/actions/workflows/${file}`;
    lines.push(image(`${name} workflow`, `${workflow}/badge.svg?branch=master`, workflow));
  }
  for (const name of BADGE_NAMES) {
    const endpoint = `https://img.shields.io/endpoint?url=${encodeURIComponent(metricJsonUrl(name))}`;
    lines.push(image(name, endpoint, `${PAGES_URL}/`));
  }
  const fixed = staticBadges(pkg);
  lines.push(image('License', staticImage(fixed.license.label, fixed.license.message), `${REPO_URL}/blob/master/LICENSE`));
  lines.push(image('Electron', staticImage(fixed.electron.label, fixed.electron.message), 'https://www.electronjs.org/'));
  lines.push(image('Node', staticImage(fixed.node.label, `>=${fixed.node.message}`), 'https://nodejs.org/'));
  lines.push(image('Allure report', staticImage('Allure', 'report'), `${PAGES_URL}/`));
  return [BLOCK_START, ...lines, BLOCK_END].join('\n');
}

/** The README with the text between the markers (markers included) replaced by `block`. */
export function replaceBadgeBlock(readme: string, block: string): string {
  const start = readme.indexOf(BLOCK_START);
  const end = readme.indexOf(BLOCK_END);
  if (start === -1 || end === -1 || end < start) throw new Error('README.md has no badge block markers');
  return readme.slice(0, start) + block + readme.slice(end + BLOCK_END.length);
}
